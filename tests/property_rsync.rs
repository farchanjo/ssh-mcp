// ---------------------------------------------------------------------------
// Strategy helpers
// ---------------------------------------------------------------------------

/// POSIX regular-file mode bits — `S_IFREG | 0o0644` is the canonical
/// shape every entry generated by the strategy carries.
const REG_MODE: u32 = 0o100_644;

/// Bound for byte-buffer fuzzing — keeps round-trip times under the
/// proptest 256-case budget reasonable on CI.
const MAX_BUF_LEN: usize = 256;

/// Strategy: a single non-empty POSIX path with letters + digits +
/// `/`. Avoids `..` and absolute prefixes — those would trip the
/// receiver-side security check ported from openrsync.
fn arb_safe_path() -> impl Strategy<Value = PathBuf> {
    "[a-z0-9]{1,8}(/[a-z0-9]{1,8}){0,3}".prop_map(PathBuf::from)
}

/// Strategy: a regular-file [`Flist`] entry with deterministic mode +
/// random size / mtime / uid / gid.
fn arb_flist_regular() -> impl Strategy<Value = Flist> {
    (
        arb_safe_path(),
        0_i64..=(1_i64 << 32),
        0_i64..=2_000_000_000_i64,
        0_u32..=65_535,
        0_u32..=65_535,
    )
        .prop_map(|(path, size, mtime, uid, gid)| {
            Flist::regular(path, size, mtime, REG_MODE, uid, gid)
        })
}

/// Strategy: a small `Vec<Flist>` of unique-path regular files.
/// Duplicate paths are filtered post-generation because the receiver
/// would deduplicate them via openrsync's `qsort` + uniqueness pass.
fn arb_flist_vec() -> impl Strategy<Value = Vec<Flist>> {
    prop_vec(arb_flist_regular(), 1..=8).prop_filter("non-unique paths", |entries| {
        let mut paths: Vec<&PathBuf> = entries.iter().map(|e| &e.path).collect();
        paths.sort();
        paths.dedup();
        paths.len() == entries.len()
    })
}

/// Strategy: arbitrary byte buffer for hash + mplex round-trip
/// fuzzing.
fn arb_byte_buf() -> impl Strategy<Value = Vec<u8>> {
    prop_vec(any::<u8>(), 0..=MAX_BUF_LEN)
}

/// Strategy: ascending sequence of positive ndx values (mirrors the
/// rsync sender's natural access pattern). The diff-encoder is
/// optimised for this access pattern and any random sequence would
/// bloat the wire to test a path that is not exercised in practice.
fn arb_ndx_ascending() -> impl Strategy<Value = Vec<i32>> {
    prop_vec(0_i32..=10_000, 0..=16).prop_map(|deltas| {
        let mut out = Vec::with_capacity(deltas.len());
        let mut acc = 0_i32;
        for d in deltas {
            // Diff must be >= 1 so the index strictly increases (the
            // codec encodes `diff = ndx - prev` and the proto-30 wire
            // shape collapses `diff == 0` ambiguously to a stale
            // `prev_positive`).
            acc = acc.saturating_add(d.saturating_add(1));
            out.push(acc);
        }
        out
    })
}

