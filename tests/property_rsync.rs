//! ADR 0011 — property tests for the v7.0 rsync hybrid transport
//! wire codec.
//!
//! These tests fuzz the deterministic encode/decode contracts of
//! every public codec under `src/adapters/rsync/wire/` against the
//! `MplexReader` / `MplexWriter` / `tokio::io::duplex` round-trip
//! pattern already used by the in-module unit tests:
//!
//! 1. `prop_flist_round_trip_proto31` — random `Vec<Flist>` (regular
//!    files only) round-trips through `send_flist` / `recv_flist`
//!    against the proto-31 16-bit `XMIT_EXTENDED_FLAGS` wire shape.
//! 2. `prop_flist_round_trip_proto27` — same property against the
//!    8-bit `FLIST_*` proto-27 wire shape.
//! 3. `prop_ndx_round_trip` — random `Vec<i32>` (positive +
//!    `NDX_DONE`) round-trips through `write_ndx` / `read_ndx` at
//!    proto 31, preserving the diff-encoded sequence.
//! 4. `prop_hash_split_combine_inverse` — `hash_fast(buf)` equals
//!    `combine_s1_s2(hash_split(buf))` for arbitrary `Vec<u8>`.
//! 5. `prop_hash_roll_matches_recompute` — rolling-window slide via
//!    `hash_roll` agrees with a fresh `hash_fast` over the new
//!    window for arbitrary buffers + window sizes.
//! 6. `prop_file_hasher_md5_proto31_matches_streaming` —
//!    `FileHasher::for_protocol(seed, 31)` produces
//!    `MD5(file_bytes)` regardless of seed for arbitrary chunked
//!    buffers.
//! 7. `prop_file_hasher_md4_proto27_seed_dependent` —
//!    `FileHasher::for_protocol(seed, 27)` produces
//!    `MD4(seed_le || file_bytes)` and is seed-sensitive.
//! 8. `prop_mplex_data_frame_round_trip` — arbitrary byte buffers
//!    survive the mplex `MSG_DATA` framing layer (header chunking
//!    capped at `MAX_PAYLOAD_LEN`).
//!
//! Run with:
//!
//! ```text
//! cargo test --features test-fixtures --test property_rsync
//! ```

